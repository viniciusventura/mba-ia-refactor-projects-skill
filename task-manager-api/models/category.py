from database import db
from models.soft_delete import SoftDeleteMixin
from utils.constants import DEFAULT_CATEGORY_COLOR
from utils.time import utc_now


class Category(SoftDeleteMixin, db.Model):
    __tablename__ = 'categories'

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(100), nullable=False)
    description = db.Column(db.String(300), nullable=True)
    color = db.Column(db.String(7), default=DEFAULT_CATEGORY_COLOR)
    created_at = db.Column(db.DateTime, default=utc_now)

    def to_dict(self):
        return {
            'id': self.id,
            'name': self.name,
            'description': self.description,
            'color': self.color,
            'created_at': str(self.created_at),
        }

    @classmethod
    def list_active(cls):
        return cls.not_deleted().order_by(cls.id).all()
